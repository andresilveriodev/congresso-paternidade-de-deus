import "server-only";
import { BlobPreconditionFailedError, get, put } from "@vercel/blob";
import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { unstable_cache } from "next/cache";
import sharp from "sharp";
import type { CongressPhoto } from "@/types/congresso";

export const UPLOAD_CACHE_TAG = "congress-direct-photos";
export const MAX_UPLOAD_BYTES = 3 * 1024 * 1024;
export const MAX_UPLOADED_PHOTOS = 2000;
const CATALOG_PATH = "congresso/catalog-v1.json";
export type UploadedPhoto = CongressPhoto & { createdAt: string; width: number; height: number };
type Catalog = { items: UploadedPhoto[] };

export function uploadStorageMode(): "local" | "vercel" | "unconfigured" {
  if (process.env.NODE_ENV !== "production" && process.env.GALLERY_STORAGE === "local") return "local";
  if (process.env.BLOB_READ_WRITE_TOKEN?.trim() || (process.env.BLOB_STORE_ID && process.env.VERCEL_OIDC_TOKEN)) return "vercel";
  return "unconfigured";
}

function localPath(key: string) {
  // All keys are generated by this module; no user-provided path is used.
  return path.join(process.cwd(), "output", "galeria-dados", key);
}

async function readCatalog(): Promise<{ items: UploadedPhoto[]; etag?: string }> {
  const mode = uploadStorageMode();
  if (mode === "unconfigured") return { items: [] };
  if (mode === "local") {
    try {
      const data = await readFile(localPath(CATALOG_PATH), "utf8");
      return { items: (JSON.parse(data) as Catalog).items, etag: createHash("sha256").update(data).digest("hex") };
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return { items: [] };
      throw error;
    }
  }
  const result = await get(CATALOG_PATH, { access: "private", useCache: false, abortSignal: AbortSignal.timeout(15000) });
  if (!result) return { items: [] };
  if (result.statusCode !== 200) throw new Error("STORAGE_UNAVAILABLE");
  return { items: (await new Response(result.stream).json() as Catalog).items, etag: result.blob.etag };
}

const cachedCatalog = unstable_cache(async () => (await readCatalog()).items, ["congress-direct-photos-v1"], { revalidate: 30, tags: [UPLOAD_CACHE_TAG] });
export async function getUploadedPhotos() {
  const mode = uploadStorageMode();
  return mode === "unconfigured" ? [] : mode === "local" ? (await readCatalog()).items : cachedCatalog();
}

async function writeImage(key: string, bytes: Buffer) {
  if (uploadStorageMode() === "local") {
    await mkdir(path.dirname(localPath(key)), { recursive: true });
    await writeFile(localPath(key), bytes);
    return;
  }
  // The path includes the hash of the encoded image; an overwrite has identical bytes.
  await put(key, bytes, { access: "private", contentType: "image/webp", addRandomSuffix: false, allowOverwrite: true, cacheControlMaxAge: 31536000, abortSignal: AbortSignal.timeout(20000) });
}

let localQueue = Promise.resolve();
async function appendPhoto(photo: UploadedPhoto): Promise<boolean> {
  if (uploadStorageMode() === "local") {
    let added = false;
    const operation = localQueue.then(async () => {
      const catalog = await readCatalog();
      if (catalog.items.some((item) => item.id === photo.id)) return;
      if (catalog.items.length >= MAX_UPLOADED_PHOTOS) throw new Error("CATALOG_FULL");
      const destination = localPath(CATALOG_PATH);
      await mkdir(path.dirname(destination), { recursive: true });
      const temporary = `${destination}.${randomUUID()}.tmp`;
      await writeFile(temporary, JSON.stringify({ items: [photo, ...catalog.items] }));
      await rename(temporary, destination);
      added = true;
    });
    localQueue = operation.catch(() => {});
    await operation;
    return added;
  }
  for (let attempt = 0; attempt < 6; attempt++) {
    const catalog = await readCatalog();
    if (catalog.items.some((item) => item.id === photo.id)) return false;
    if (catalog.items.length >= MAX_UPLOADED_PHOTOS) throw new Error("CATALOG_FULL");
    try {
      await put(CATALOG_PATH, JSON.stringify({ items: [photo, ...catalog.items] }), {
        access: "private", contentType: "application/json", addRandomSuffix: false,
        allowOverwrite: Boolean(catalog.etag), ...(catalog.etag ? { ifMatch: catalog.etag } : {}),
        cacheControlMaxAge: 60, abortSignal: AbortSignal.timeout(15000)
      });
      return true;
    } catch (error) {
      if (!(error instanceof BlobPreconditionFailedError) && !(!catalog.etag && error instanceof Error && /already exists/i.test(error.message))) throw error;
    }
  }
  throw new Error("STORAGE_BUSY");
}

export async function publishUploadedPhoto(file: File, day: string) {
  if (uploadStorageMode() === "unconfigured") throw new Error("STORAGE_UNCONFIGURED");
  if (!file.size || file.size > MAX_UPLOAD_BYTES) throw new Error("INVALID_IMAGE");
  const input = Buffer.from(await file.arrayBuffer());
  let large: Buffer;
  let thumbnail: Buffer;
  let width: number;
  let height: number;
  try {
    const source = sharp(input, { limitInputPixels: 40_000_000, animated: false });
    const metadata = await source.metadata();
    if (!["jpeg", "png", "webp"].includes(metadata.format ?? "") || (metadata.pages ?? 1) > 1) throw new Error();
    const encoded = await source.rotate().resize({ width: 1920, height: 1920, fit: "inside", withoutEnlargement: true }).webp({ quality: 88 }).toBuffer({ resolveWithObject: true });
    large = encoded.data;
    width = encoded.info.width;
    height = encoded.info.height;
    thumbnail = await sharp(large).resize({ width: 640, height: 480, fit: "inside", withoutEnlargement: true }).webp({ quality: 80 }).toBuffer();
  } catch { throw new Error("INVALID_IMAGE"); }
  const id = `upload_${createHash("sha256").update(large).digest("hex")}`;
  const existing = (await readCatalog()).items.find((item) => item.id === id);
  if (existing) return { photo: existing, duplicate: true };
  const title = file.name.replace(/\.[^.]+$/, "").replace(/[_-]+/g, " ").trim().slice(0, 140) || "Foto do Congresso";
  const photo: UploadedPhoto = {
    id, title, alt: `${title}${day ? ` — ${day}` : ""}`, ...(day ? { day } : {}), width, height,
    createdAt: new Date().toISOString(), imageUrl: `/api/congresso/fotos/${id}?size=large`,
    thumbnailUrl: `/api/congresso/fotos/${id}?size=thumbnail`
  };
  // Publish the catalog only after both complete images have been persisted.
  await Promise.all([writeImage(`congresso/images/${id}/large.webp`, large), writeImage(`congresso/images/${id}/thumbnail.webp`, thumbnail)]);
  return { photo, duplicate: !await appendPhoto(photo) };
}

export async function getUploadedPhotoBytes(id: string, thumbnail: boolean) {
  if (!/^upload_[a-f0-9]{64}$/.test(id)) return null;
  const catalog = await getUploadedPhotos();
  if (!catalog.some((photo) => photo.id === id)) return null;
  const key = `congresso/images/${id}/${thumbnail ? "thumbnail" : "large"}.webp`;
  if (uploadStorageMode() === "local") {
    try { return await readFile(localPath(key)); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return null; throw error; }
  }
  const result = await get(key, { access: "private", abortSignal: AbortSignal.timeout(15000) });
  return result?.statusCode === 200 ? Buffer.from(await new Response(result.stream).arrayBuffer()) : null;
}
